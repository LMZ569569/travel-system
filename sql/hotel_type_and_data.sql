USE travel_plan;

-- 1. 给 hotel 表新增「类型」字段（若已存在则跳过）
SET @exist := (SELECT COUNT(*) FROM information_schema.COLUMNS
               WHERE TABLE_SCHEMA = 'travel_plan' AND TABLE_NAME = 'hotel' AND COLUMN_NAME = 'type');
SET @sql := IF(@exist = 0,
    'ALTER TABLE hotel ADD COLUMN type VARCHAR(20) DEFAULT ''舒适型'' COMMENT ''酒店类型：经济型/舒适型/豪华型/民宿'' AFTER city',
    'SELECT 1');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 2. 给已有的示例酒店补充类型
UPDATE hotel SET type = '豪华型' WHERE name LIKE '%希尔顿%' OR name LIKE '%华尔道夫%' OR name LIKE '%香格里拉%' OR name LIKE '%国宾馆%' OR name LIKE '%威斯汀%' OR name LIKE '%白天鹅%';
