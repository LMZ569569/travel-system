# 获取所有城市及其景点
rows = run_sql("SELECT id, city, name FROM scenic_spot ORDER BY city, id")
lines = rows.split('\n')

spots = []
for line in lines:
    parts = line.strip().split('\t')
    if len(parts) >= 3:
        spots.append({'id': parts[0].strip(), 'city': parts[1].strip(), 'name': parts[2].strip()})

print(f"共 {len(spots)} 个景点")

# 按城市分组统计
city_groups = {}
for s in spots:
    city_groups.setdefault(s['city'], []).append(s)

updated = 0
# 对每个城市，更新景点名称
for city, spot_list in city_groups.items():
    real_names = REAL_SPOTS.get(city, None)
    
    for i, s in enumerate(spot_list):
        if real_names and i < len(real_names):
            new_name = real_names[i]
        else:
            # 生成备用名称
            tmpl = random.choice(BACKUP_TEMPLATES)
            new_name = tmpl.replace('{city}', city)
        
        # 确保名称不重复
        # 生成描述
        desc_tmpl = random.choice(DESC_TEMPLATES)
        desc = desc_tmpl.replace('{city}', city)
        desc = desc[:100]
        
        # 更新数据库
        name_safe = new_name.replace("'", "''")
        desc_safe = desc.replace("'", "''")
        sql = f"UPDATE scenic_spot SET name='{name_safe}', description='{desc_safe}' WHERE id={s['id']}"
        run_sql(sql)
        updated += 1
        
        if updated % 500 == 0:
            print(f"  已更新 {updated}/{len(spots)}")

print(f"\n更新完成！共更新 {updated} 个景点名称")

