    depart_time VARCHAR(10) NOT NULL,
    arrive_time VARCHAR(10) NOT NULL,
    price DECIMAL(10,2) DEFAULT 0,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

