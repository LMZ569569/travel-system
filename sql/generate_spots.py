# 开放时间模板
open_times = ["08:00-17:30", "08:30-17:00", "09:00-17:00", "08:00-18:00", "全天开放", "09:00-21:00"]

# 等级分布
levels = ["4A", "4A", "4A", "3A", "3A", "5A", "4A"]

def gen_coord(city, seed_offset):
    h = hash(city + str(seed_offset)) & 0xFFFFFFFF
    random.seed(h)
    lat = 28.0 + random.random() * 18.0
    lng = 100.0 + random.random() * 25.0
    return round(lat, 6), round(lng, 6)

def gen_price(seed):
    random.seed(seed)
    # 0~30% 免费，其余收费
    if random.random() < 0.3:
        return 0.00
    return round(random.uniform(10, 200), 2)

def gen_rating(seed):
    random.seed(seed + 100)
    return round(3.5 + random.random() * 1.5, 1)

def gen_visit_duration(seed):
    random.seed(seed + 200)
    return round(2.0 + random.random() * 4.0, 1)

def gen_description(name, city, level):
    return f"{city}著名{level}级旅游景区，{name}周边核心景点，深受游客喜爱"

lines = []
count = 0
for city, province in cities:
    needed = 7  # 每个城市至少7个景点
    random.seed(hash(city + "_spots") & 0xFFFFFFFF)
    used_names = set()
    for i in range(needed):
        # 选一个模板
        tmpl_group = spot_templates[i % len(spot_templates)]
        tmpl = tmpl_group[random.randint(0, len(tmpl_group) - 1)]
        name = tmpl.format(city=city)
        # 避免重名
        if name in used_names:
            name = f"{city}{city}名胜第{i+1}景"
        used_names.add(name)
        
        level = levels[i % len(levels)]
        lat, lng = gen_coord(city, i)
        price = gen_price(count + i)
        rating = gen_rating(count + i)
        visit_dur = gen_visit_duration(count + i)
        open_time = open_times[i % len(open_times)]
        desc = gen_description(name, city, level)
        addr = f"{city}市区第{i+1}号"
        
        lines.append(f"('{name}', '{desc}', '{province}', '{city}', '{level}', '{addr}', {lat}, {lng}, {price:.2f}, '{open_time}', {rating}, {visit_dur:.1f})")
        count += 1

